"""
Retest Engine and Automated Regression Test Generator.

Generates standalone executable pytest / Python regression scripts from verified findings
and validates that applied fixes successfully remediate the vulnerability.
See plan sections 60, 61 and Phase F.
"""

from dataclasses import dataclass
from typing import Dict, Any, List, Optional
import httpx

from security_agent.model.schemas import Finding


@dataclass
class RetestResult:
    finding_id: str
    is_remediated: bool
    status_code: int
    notes: str
    retest_timestamp: str


class RetestEngine:
    """
    Automates retesting of findings and creates regression test code.
    """
    def generate_regression_test_script(self, finding: Finding) -> str:
        """
        Generates a standalone pytest script that can be committed to a repository's CI pipeline.
        """
        script = f'''"""
Automated Security Regression Test for {finding.id}: {finding.title}
Generated by Buzzard Code
"""

import httpx
import pytest

TARGET_ASSET = "{finding.affected_asset}"

def test_security_remediation_{finding.id.replace("-", "_")}():
    """
    Verifies that {finding.title} is properly mitigated.
    """
    client = httpx.Client(timeout=10.0, verify=False)
    
    # Send verification probe
    response = client.get(TARGET_ASSET)
    
    # Assert defensive boundaries
    assert response.status_code != 500, "Server must not trigger unhandled 500 exceptions on security probes"
    
    # Check for absence of error signatures
    body_lower = response.text.lower()
    for signature in ["sql syntax", "operationalerror", "ora-01756", "mysqlclient", "<script>"]:
        assert signature not in body_lower, f"Defensive boundary failure: signature '{{signature}}' leaked in response"
'''
        return script

    def execute_live_retest(self, finding: Finding) -> RetestResult:
        """
        Executes a live HTTP probe against the affected asset to confirm remediation status.
        """
        now = __import__("datetime").datetime.now(__import__("datetime").timezone.utc).isoformat()
        try:
            target = finding.affected_asset
            if not target.startswith(("http://", "https://")):
                target = f"http://{target}"

            client = httpx.Client(timeout=10.0, verify=False)
            response = client.get(target)

            body = response.text.lower()
            vuln_detected = any(s in body for s in ["sql syntax", "operationalerror", "fatal error"])

            if not vuln_detected and response.status_code in (200, 400, 401, 403, 404):
                return RetestResult(
                    finding_id=finding.id,
                    is_remediated=True,
                    status_code=response.status_code,
                    notes=f"Remediation confirmed: Endpoint returned HTTP {response.status_code} with no vulnerability signatures.",
                    retest_timestamp=now
                )
            else:
                return RetestResult(
                    finding_id=finding.id,
                    is_remediated=False,
                    status_code=response.status_code,
                    notes="Vulnerability still present: error signatures or unexpected response detected.",
                    retest_timestamp=now
                )
        except Exception as e:
            return RetestResult(
                finding_id=finding.id,
                is_remediated=False,
                status_code=0,
                notes=f"Retest failed to connect to target: {e}",
                retest_timestamp=now
            )
